// reverse nums 
let nums = [5, 2, 9, 1, 5, 6];
// Reverse the array
nums.reverse();
console.log("Reversed array:", nums);


// reverse using toReversed() method
let nums2 = [5, 2, 9, 1, 5, 6];
let nums3 = nums2.toReversed();
console.log("Original array:", nums2);
console.log("Reversed array using toReversed():", nums3);

