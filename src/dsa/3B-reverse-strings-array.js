// reverse strings array
let strings = ["apple", "banana", "cherry", "date", "elderberry"];
// Reverse the array
strings.reverse();
console.log("Reversed strings array:", strings);


// reverse using toReversed() method
let strings2 = ["apple", "banana", "cherry", "date", "elderberry"]; 
let strings3 = strings2.toReversed();
console.log("Original strings array:", strings2);
console.log("Reversed strings array using toReversed():", strings3);